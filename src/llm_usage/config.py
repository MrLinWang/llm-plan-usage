"""Configuration load/save for llm-usage.

Config lives at ``./config.toml`` in the current working directory (TOML).
Reads use stdlib ``tomllib``; writes use ``tomli_w``.  API keys may use an
``env:VARNAME`` prefix to reference environment variables instead of storing
plaintext on disk.  Override the path with the ``LLM_USAGE_CONFIG`` env var.
"""

from __future__ import annotations

import os
import tempfile
import threading
import tomllib
from collections.abc import Callable, Iterable
from pathlib import Path
from typing import Any, TypeVar

import tomli_w

from llm_usage.config_schema import ConfigFormatError, to_accounts_config, to_runtime_config
from llm_usage.platform_keys import (
    PlatformKeyConflict,
    canonical_platform_key,
)

CONFIG_PATH = Path.cwd() / "config.toml"

# 进程内互斥:llm-usage web 单 Uvicorn 进程,并发 FastAPI worker 线程共享此锁,
# 保证所有 config.toml 读-改-写在同一临界区内串行(避免丢失更新)。
_CONFIG_LOCK = threading.Lock()

_T = TypeVar("_T")


def _set_sensitive_permissions(path: Path) -> None:
    """Best-effort 0600(凭证明文,收敛文件权限;幂等,失败不阻断)。"""
    try:
        path.chmod(0o600)
    except OSError:
        pass


def _atomic_write_bytes(path: Path, payload: bytes) -> None:
    """原子写:同目录临时文件 + os.replace,读者永远看到完整旧文件或完整新文件。"""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            delete=False,
            dir=path.parent,
            prefix=f".{path.name}.",
            suffix=".tmp",
        ) as fh:
            tmp_path = Path(fh.name)
            fh.write(payload)
            fh.flush()
            os.fsync(fh.fileno())
        _set_sensitive_permissions(tmp_path)
        os.replace(tmp_path, path)
        tmp_path = None
        _set_sensitive_permissions(path)
    finally:
        if tmp_path is not None:
            try:
                tmp_path.unlink()
            except OSError:
                pass


def _write_config_unlocked(config: dict[str, Any], path: Path) -> None:
    """先完整序列化再原子落盘;序列化失败不会触碰目标文件。"""
    _atomic_write_bytes(path, format_config(config).encode("utf-8"))


def format_config(config: dict[str, Any]) -> str:
    """Render accounts as tables consistently, independent of credential length."""
    canonical = to_accounts_config(config)
    blocks: list[str] = []

    def key_part(key: str) -> str:
        return tomli_w.dumps({key: 0}).removesuffix(" = 0\n")

    def emit(table: dict[str, Any], path: list[str], array: bool = False) -> None:
        literals: dict[str, Any] = {}
        children: list[tuple[str, Any]] = []
        fields = list(table)
        if len(path) == 2 and path[0] == "platforms":
            priority = ["enabled", "display_name", "base_url"]
            fields = [key for key in priority if key in table]
            fields += sorted(key for key in table if key not in priority and key != "accounts")
            if "accounts" in table:
                fields.append("accounts")
        elif array:
            fields = (["name"] if "name" in table else []) + sorted(
                key for key in table if key != "name"
            )
        for key in fields:
            value = table[key]
            if isinstance(value, dict) or (
                isinstance(value, list) and value
                and all(isinstance(item, dict) for item in value)
            ):
                children.append((key, value))
            else:
                literals[key] = value
        block = ""
        if path and (literals or not children or array):
            name = ".".join(key_part(part) for part in path)
            block = f"[[{name}]]\n" if array else f"[{name}]\n"
        block += tomli_w.dumps(literals)
        if block:
            blocks.append(block.rstrip("\n"))
        for key, value in children:
            child_path = [*path, key]
            if isinstance(value, dict):
                emit(value, child_path)
            else:
                for item in value:
                    emit(item, child_path, array=True)

    emit(canonical, [])
    return "\n\n".join(blocks) + ("\n" if blocks else "")

